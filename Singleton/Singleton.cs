using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

// https://csharpindepth.com/Articles/Singleton#cctor  by Jon Skeet

namespace Singleton
{
    // It's not as lazy as the other implementations. In particular, if you have static members other than Instance
    // the first reference to those members will involve creating the instance.
    // But in case "Singleton instance" is the only static member - it will be lazily initialized on first reference to it.
    public sealed class Singleton
    {
        private static readonly Singleton instance = new Singleton(); // thread safe, eager loading (kind of lazy)

        // static constructor "static Singleton()" to tell C# compiler not to mark type as beforefieldinit.

            // Update:
            // use Ildasm to see that it gets autogenerated
            // Static field initializers cause the compiler to emit a .cctor method.
        //static Singleton()
        //{
        //    Console.WriteLine("in static ctor");
        //}

        private Singleton()
        {
            Console.WriteLine("in ctor");
        }

        public static Singleton Instance
        {
            get
            {
                return instance;
            }
        }
    }
}
